package com.coliclic.backoffice.user;

import com.coliclic.backoffice.user.entity.User;
import org.hibernate.boot.MetadataSources;
import org.hibernate.boot.registry.StandardServiceRegistryBuilder;
import org.hibernate.boot.model.naming.CamelCaseToUnderscoresNamingStrategy;
import org.junit.jupiter.api.Test;

import java.sql.DriverManager;
import java.util.UUID;

import static org.assertj.core.api.Assertions.assertThat;

class UserRowVersionMigrationTest {
    @Test
    void schemaUpdateInitializesTheVersionOfExistingAccounts() throws Exception {
        String url = "jdbc:h2:mem:user-version-" + UUID.randomUUID() + ";DB_CLOSE_DELAY=-1";
        try (var connection = DriverManager.getConnection(url, "sa", ""); var sql = connection.createStatement()) {
            sql.execute("create table users (id bigint generated by default as identity primary key, "
                    + "first_name varchar(255) not null, last_name varchar(255) not null, "
                    + "email varchar(255) not null, password varchar(255) not null, role varchar(255) not null)");
            sql.execute("insert into users (first_name, last_name, email, password, role) "
                    + "values ('Ada', 'Lovelace', 'legacy@migration.test', 'original-hash', 'USER')");
        }
        var registry = new StandardServiceRegistryBuilder()
                .applySetting("hibernate.connection.url", url)
                .applySetting("hibernate.connection.username", "sa")
                .applySetting("hibernate.connection.password", "")
                .applySetting("hibernate.hbm2ddl.auto", "update")
                .applySetting("hibernate.physical_naming_strategy", CamelCaseToUnderscoresNamingStrategy.class.getName())
                .build();
        try (var factory = new MetadataSources(registry).addAnnotatedClass(User.class).buildMetadata().buildSessionFactory();
             var session = factory.openSession()) {
            var transaction = session.beginTransaction();
            User legacy = session.find(User.class, 1L);
            assertThat(legacy.getRowVersion()).isZero();
            assertThat(legacy.getPassword()).isEqualTo("original-hash");
            legacy.setPhone("+33123456789");
            transaction.commit();
            session.clear();
            assertThat(session.find(User.class, 1L).getRowVersion()).isEqualTo(1);
        } finally {
            StandardServiceRegistryBuilder.destroy(registry);
        }
    }
}
